package ru.yanin.shared.message_broker.producer;

/**
 * Базовый интерфейс для всех продюсеров (производителей) сообщений в RabbitMQ.
 * <p>
 * Предоставляет контракт на отправку сообщений в обменники (Exchanges) RabbitMQ.
 * Реализации этого интерфейса должны инкапсулировать в себе логику маршрутизации.
 *
 * @param <T> тип тела сообщения (payload), которое будет отправлено продюсером.
 *           Обычно это DTO (Data Transfer Object) или доменная сущность.
 */
public interface Producer<T> {

    /**
     * Отправляет сообщение в очередь RabbitMQ через сконфигурированный обменник.
     * <p>
     * Метод синхронно публикует сообщение в брокер. В зависимости от конфигурации
     * {@code RabbitTemplate}, он может быть синхронным (ожидание подтверждения)
     * или асинхронным (публикация без ожидания).
     *
     * @param message тело сообщения, которое необходимо отправить. Не может быть {@code null}.
     * @throws IllegalArgumentException если передан {@code null} в качестве сообщения.
     */
    void send(T message);
}
